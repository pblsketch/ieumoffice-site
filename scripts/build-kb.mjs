// Builds lib/kb-data.js, the knowledge the question helper answers from.
//
//   npm run kb                       # the app's latest GitHub release
//   npm run kb -- --ref v0.12.3      # a given tag of the app repository
//
// Sources: the app's Korean help topics (the manual opened with F1), README and
// PRIVACY read from the app repository at the release tag with `git show`, so
// the branch or unsaved work in that checkout never leaks in; the latest
// release notes from GitHub; and this site's own pages.
//
// The app repository is ../openoffice next to this site; IEUM_APP_REPO points
// elsewhere. Run `git fetch --tags` there first if the tag is missing.

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { parse } from 'node-html-parser'

const SITE = resolve(import.meta.dirname, '..')
const APP_REPO = process.env.IEUM_APP_REPO ?? resolve(SITE, '../openoffice')
const GITHUB_REPO = 'pblsketch/openoffice'
const SITE_URL = 'https://ieumoffice.com'
const RELEASE_NOTES = 5
const MAX_CHUNK = 1500
const HELP_DIR = 'apps/shell/src/renderer/src/i18n/help/topics'

const args = process.argv.slice(2)
const refArg = args.includes('--ref') ? args[args.indexOf('--ref') + 1] : null

const releases = await githubJson(`repos/${GITHUB_REPO}/releases?per_page=${RELEASE_NOTES + 5}`)
const published = releases.filter((r) => !r.draft)
const ref = refArg ?? published.find((r) => !r.prerelease)?.tag_name ?? published[0]?.tag_name
if (!ref) throw new Error('no release found on GitHub; pass --ref <tag>')
try {
  git('rev-parse', '--verify', '--quiet', `${ref}^{commit}`)
} catch {
  throw new Error(`${ref} is not in ${APP_REPO}; run "git fetch --tags" there or set IEUM_APP_REPO`)
}

const chunks = []

// --- the in-app manual -------------------------------------------------------
const topics = git('ls-tree', '--name-only', ref, `${HELP_DIR}/`)
  .split('\n')
  .filter((f) => f.endsWith('.ko.md'))
for (const file of topics) {
  const md = brandText(git('show', `${ref}:${file}`))
  const title = md.match(/^#\s+(.+)$/m)?.[1].trim() ?? file
  chunks.push(
    ...chunkMarkdown(md, {
      source: `앱 도움말 › ${title}`,
      url: null,
      anchors: 'none',
    }),
  )
}

// --- README and the full privacy list -----------------------------------------
chunks.push(
  ...chunkMarkdown(git('show', `${ref}:README.md`), {
    source: 'README',
    url: `https://github.com/${GITHUB_REPO}`,
    anchors: 'github',
  }),
  ...chunkMarkdown(git('show', `${ref}:PRIVACY.md`), {
    source: 'PRIVACY.md',
    url: `https://github.com/${GITHUB_REPO}/blob/main/PRIVACY.md`,
    anchors: 'github',
  }),
)

// --- release notes -----------------------------------------------------------
for (const release of published.slice(0, RELEASE_NOTES)) {
  const date = release.published_at?.slice(0, 10) ?? ''
  chunks.push(
    ...chunkMarkdown(release.body ?? '', {
      // what a release said about itself; later releases may have changed it
      source: `${release.tag_name} 업데이트 기록 (${date} 당시)`,
      url: release.html_url,
      anchors: 'none',
    }),
  )
}

// --- this site's pages -------------------------------------------------------
const PAGES = [
  ['index.html', '/', '이음오피스 소개'],
  ['install.html', '/install', '설치 도움말'],
  ['connect.html', '/connect', 'AI 연결 도움말'],
  ['updates.html', '/updates', '업데이트 소식'],
  ['story.html', '/story', '만든 이야기'],
  ['public/privacy.html', '/privacy.html', '개인정보 처리방침'],
  ['public/legal.html', '/legal.html', '법적 고지'],
]
for (const [file, path, name] of PAGES) {
  const md = htmlToMarkdown(readFileSync(resolve(SITE, file), 'utf8'))
  chunks.push(...chunkMarkdown(md, { source: name, url: `${SITE_URL}${path}`, anchors: 'explicit' }))
}

chunks.forEach((chunk, i) => (chunk.id = i))
// no build date: the same sources must give the same file, so the daily CI run
// (.github/workflows/kb.yml) commits only when something really changed
const kb = { version: ref, chunks }

mkdirSync(resolve(SITE, 'lib'), { recursive: true })
writeFileSync(
  resolve(SITE, 'lib/kb-data.js'),
  `// Generated by scripts/build-kb.mjs from ${GITHUB_REPO} ${ref}. Do not edit; run \`npm run kb\`.\n` +
    `export default {\n  version: ${JSON.stringify(kb.version)},\n  chunks: [\n` +
    chunks.map((c) => `    ${JSON.stringify(c)},`).join('\n') +
    `\n  ],\n}\n`,
)
const chars = chunks.reduce((n, c) => n + c.text.length, 0)
console.log(`lib/kb-data.js: ${chunks.length} pieces, ${chars.toLocaleString()} characters, app ${ref}`)

// -----------------------------------------------------------------------------

function git(...gitArgs) {
  return execFileSync('git', ['-C', APP_REPO, ...gitArgs], { encoding: 'utf8', maxBuffer: 64 << 20 })
}

async function githubJson(path) {
  const res = await fetch(`https://api.github.com/${path}`, {
    headers: {
      Accept: 'application/vnd.github+json',
      'User-Agent': 'ieumoffice-site-kb',
      // CI passes its token so the hourly limit on anonymous API calls doesn't bite
      ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
    },
  })
  if (!res.ok) throw new Error(`GitHub ${path}: ${res.status}`)
  return res.json()
}

// The app's help files say "GenOffice" where the product names itself and swap
// it for the shown name at runtime; this mirrors brandText() in the app's
// packages/i18n/src/product.ts for Korean.
function brandText(text) {
  return text.replace(/\{\{GenOffice\}\}|GenOffice/g, (match, offset) => {
    if (match !== 'GenOffice') return 'GenOffice'
    const before = text.charAt(offset - 1)
    const after = text.slice(offset + match.length, offset + match.length + 2)
    if (/[A-Za-z0-9_]/.test(before) || /^[A-Za-z0-9]/.test(after)) return match
    if (/[\\/]/.test(before) || /^(?:[\\/]|[-_][A-Za-z0-9<]|\.[A-Za-z0-9])/.test(after)) return 'IeumOffice'
    return '이음오피스'
  })
}

// GitHub's heading anchor: lower case, punctuation dropped, spaces to dashes
function githubSlug(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s/g, '-')
}

function cleanInline(text) {
  return text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)/g, '')
    .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '$1 ($2)')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
}

/** markdown → pieces of at most MAX_CHUNK characters, each titled with its heading path */
function chunkMarkdown(md, { source, url, anchors }) {
  const out = []
  const path = []
  let anchor = null
  let lines = []
  let fence = false

  const flush = () => {
    const body = cleanInline(lines.join('\n'))
      .replace(/\n{3,}/g, '\n\n')
      .trim()
    lines = []
    if (body.replace(/\s/g, '').length < 20) return
    const title = [source, ...path.filter(Boolean)].join(' › ')
    const link = url && anchor ? `${url}#${anchor}` : url
    for (const text of splitLong(body)) out.push({ title, url: link, text })
  }

  for (const line of md.replace(/\r\n/g, '\n').split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence
    const heading = !fence && line.match(/^(#{1,4})\s+(.+?)(?:\s+\{#([\w-]+)\})?\s*#*\s*$/)
    if (!heading) {
      // tables are padded into aligned columns; the padding is most of their length
      const table = !fence && line.trimStart().startsWith('|')
      lines.push(table ? line.replace(/\s{2,}/g, ' ').replace(/-{3,}/g, '---') : line)
      continue
    }
    flush()
    const level = heading[1].length
    const text = cleanInline(heading[2]).replace(/[*`]/g, '').trim()
    path.length = Math.max(0, level - 1)
    // the first heading is the document's own title; the source already names it
    path[level - 1] = level === 1 ? null : text
    if (anchors === 'explicit') anchor = heading[3] ?? anchor
    else if (anchors === 'github') anchor = level === 1 ? null : githubSlug(heading[2])
  }
  flush()
  return out
}

/** split at blank lines; a table or list too long on its own splits by line, keeping a table's header */
function splitLong(body) {
  if (body.length <= MAX_CHUNK) return [body]
  const pieces = []
  let current = ''
  const push = (part) => {
    if (current && current.length + part.length + 2 > MAX_CHUNK) {
      pieces.push(current)
      current = ''
    }
    current = current ? `${current}\n\n${part}` : part
  }
  for (const para of body.split(/\n{2,}/)) {
    if (para.length <= MAX_CHUNK) {
      push(para)
      continue
    }
    const rows = para.split('\n')
    const header = rows[0].startsWith('|') && /^\|?\s*:?-/.test(rows[1] ?? '') ? rows.slice(0, 2) : []
    let block = []
    for (const row of rows.slice(header.length)) {
      const size = [...header, ...block, row].join('\n').length
      if (block.length && size > MAX_CHUNK) {
        push([...header, ...block].join('\n'))
        block = []
      }
      block.push(row)
    }
    if (block.length) push([...header, ...block].join('\n'))
  }
  if (current) pieces.push(current)
  return pieces
}

/** a site page → markdown with `{#id}` anchors; drops the redrawn demo screens and page chrome */
function htmlToMarkdown(html) {
  const root = parse(html, { comment: false })
  const body = root.querySelector('main') ?? root.querySelector('body') ?? root
  for (const el of body.querySelectorAll(
    'script, style, svg, noscript, template, header.nav, nav, footer, .player-screen, .player-bar, [aria-hidden="true"]',
  ))
    el.remove()

  const BLOCK = new Set(['p', 'div', 'section', 'article', 'ul', 'ol', 'table', 'tr', 'blockquote', 'figure', 'figcaption', 'details', 'aside', 'dl', 'dd', 'dt'])
  const out = []
  const nearestId = (el) => {
    for (let node = el; node; node = node.parentNode) if (node.id) return node.id
    return null
  }
  const walk = (node) => {
    if (node.nodeType === 3) {
      out.push(node.text.replace(/\s+/g, ' '))
      return
    }
    if (node.nodeType !== 1) return
    const tag = node.rawTagName?.toLowerCase()
    const heading = tag?.match(/^h([1-4])$/)
    if (heading || tag === 'summary') {
      const level = heading ? Number(heading[1]) : 3
      const id = nearestId(node)
      const text = node.text.replace(/\s+/g, ' ').trim()
      if (text) out.push(`\n\n${'#'.repeat(level)} ${text}${id ? ` {#${id}}` : ''}\n\n`)
      return
    }
    if (tag === 'br') out.push('\n')
    if (tag === 'li') out.push('\n- ')
    if (tag === 'td' || tag === 'th') out.push(' | ')
    if (BLOCK.has(tag)) out.push('\n\n')
    for (const child of node.childNodes) walk(child)
    if (BLOCK.has(tag)) out.push('\n\n')
    if (tag === 'a') {
      const href = node.getAttribute('href') ?? ''
      if (/^https?:/.test(href) && !node.text.includes(href)) out.push(` (${href})`)
    }
  }
  walk(body)
  return out
    .join('')
    .split('\n')
    .map((line) => line.replace(/[ \t]+/g, ' ').trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
}
